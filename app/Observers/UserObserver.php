    public function updated(User $user): void
    {
        if ($user->wasChanged('password')) {
            $user->events()->create([
                'event_type' => 'password_updated',
                'ip_address' => request()->ip(),
                'user_agent' => request()->userAgent(),
            ]);
        }
    }

